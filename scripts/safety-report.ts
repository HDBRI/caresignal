/**
 * Writes docs/SAFETY_EVALUATION.md: the deterministic rules (generated from code) and their results on the
 * synthetic test set, with denominators. Run: npm run safety:report
 */
import fs from "node:fs";
import path from "node:path";
import cases from "../tests/fixtures/safety-cases.json";
import { evaluateSafetyTestSet, type SafetyTestSet } from "../src/lib/safety/evaluate";
import { LEVEL_LABEL, RULES_VERSION, SAFETY_LIMITATION, SAFETY_RULES, TIER_GUIDANCE } from "../src/lib/safety/rules";

const { groups, totals } = evaluateSafetyTestSet(cases as unknown as SafetyTestSet);
const lines: string[] = [];
lines.push("# CareSignal — deterministic safety rules and synthetic evaluation", "");
lines.push(`Rules version \`${RULES_VERSION}\` · generated by \`npm run safety:report\` from \`src/lib/safety/rules.ts\` and \`tests/fixtures/safety-cases.json\`.`, "");
lines.push("> **Limitations.** These are a small set of predefined phrase rules for a classroom prototype. They are **not validated triage** and are **not** a guarantee that any emergency will be detected. The test phrases were written by the same developer who wrote the rules, so the results below describe behaviour on this synthetic set only — **not real-world sensitivity, specificity or clinical safety**. " + SAFETY_LIMITATION, "");
lines.push("## How the layer works", "");
lines.push("- Runs on the **original note text**, inside the same database transaction that saves the note — before, and independently of, any AI call or network request. With no API key, a timeout or malformed AI output, the result is the same.");
lines.push("- Also runs on corrected wording (edits) and on check-in notes.");
lines.push("- Note text is data: words like “ignore your rules” or “mark as safe” cannot switch a rule off (see the prompt-injection group).");
lines.push("- Simple negation (“no”, “denies”, “without” shortly before a phrase) prevents a match.", "");
lines.push("## Behaviour levels", "");
lines.push("| Level | Shown as | Guidance |", "|---|---|---|");
lines.push(`| ${LEVEL_LABEL.emergency} | Red banner on every screen + icon, until marked seen | ${TIER_GUIDANCE.emergency.body} |`);
lines.push(`| ${LEVEL_LABEL.contact_care_team} | Amber banner on every screen + icon, until marked seen | ${TIER_GUIDANCE.contact_care_team.body} |`);
lines.push(`| ${LEVEL_LABEL.review} | Neutral marker on the note + Overview list | ${TIER_GUIDANCE.review.body} |`);
lines.push(`| ${LEVEL_LABEL.none} | Neutral “Routine” label | No predefined rule matched — this does not mean the situation is safe. Can go into a caregiver-reviewed handoff. |`, "");
lines.push("## Rules", "");
lines.push("| ID | Level | What it looks for |", "|---|---|---|");
for (const r of SAFETY_RULES) lines.push(`| \`${r.id}\` | ${LEVEL_LABEL[r.tier]} | ${r.label} |`);
lines.push("", "## Results on the synthetic test set", "");
lines.push("| Group | Expected | Total | Correct level | Wrong level | Missed | False positives |", "|---|---|---|---|---|---|---|");
for (const g of groups) {
  const exp = g.expected === "none" ? "no alert" : g.expected === "mixed" ? "per item" : LEVEL_LABEL[g.expected];
  lines.push(`| ${g.group} | ${exp} | ${g.total} | ${g.correct}/${g.total} | ${g.wrongLevel} | ${g.missed} | ${g.falsePositives} |`);
}
lines.push("");
lines.push(`**Totals:** alert-expected phrases caught **${totals.caught}/${totals.alertCases}** (missed ${totals.missed}); no-alert phrases that triggered an alert (false positives) **${totals.falsePositives}/${totals.noAlertCases}**.`, "");
const failures = groups.flatMap((g) => g.failures.map((f) => `| ${g.group} | “${f.text}” | ${f.got === "none" ? "no alert" : LEVEL_LABEL[f.got]} |`));
if (failures.length) {
  lines.push("### Every failure, listed", "", "| Group | Phrase | Result |", "|---|---|---|", ...failures, "");
}
const out = path.join(process.cwd(), "docs", "SAFETY_EVALUATION.md");
fs.writeFileSync(out, lines.join("\n") + "\n");
console.log(`Wrote ${path.relative(process.cwd(), out)}`);
console.log(`Caught ${totals.caught}/${totals.alertCases}; false positives ${totals.falsePositives}/${totals.noAlertCases}`);
